function emitVendorLogos() {
  const found = Object.entries(VENDOR_FILES).filter(([, path]) =>
    existsSync(join("public", path)),
  );
  writeFileSync(
    join("src", "data", "vendor-logos.ts"),
    `/**
 * Vendor marks that are actually on file.
 *
 * Generated by scripts/build-cards.mjs — do not edit. Drop a vendor PNG into
 * public/logos (autodesk.png, microsoft.png, …) and run the script again; the
 * cards pick it up and stop falling back to the wordmark set as type.
 */
export const VENDOR_LOGOS: Record<string, string> = {
${found.map(([vendor, path]) => `  ${JSON.stringify(vendor)}: ${JSON.stringify(path)},`).join("\n")}
};

export function vendorLogo(vendor?: string): string | undefined {
  return vendor ? VENDOR_LOGOS[vendor] : undefined;
}

export default VENDOR_LOGOS;
`,
  );
  console.log(`vendor logos on file: ${found.length ? found.map(([v]) => v).join(", ") : "none"}`);
}

