/* Extraction                                                          */
/* ------------------------------------------------------------------ */

/** `style="a: b; c: d"` → a React style object, as source text. */
function styleToObject(css) {
  const entries = css
    .split(";")
    .map((rule) => rule.trim())
    .filter(Boolean)
    .map((rule) => {
      const at = rule.indexOf(":");
      const property = rule.slice(0, at).trim();
      const value = rule.slice(at + 1).trim();
      const key = property.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
      return `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`;
    });
  return `{\n${entries.join("\n")}\n}`;
}

/**
 * Give every driven attribute a valid starting value.
 *
 * A card authors these empty — cx="" — and fills them on the first frame. That
 * is fine once the scene is running, but the browser parses the markup before
 * then and complains about every one of them. Seeding a zero costs nothing:
 * the node is transparent until the frame that gives it a real value.
 */
const ATTR_SEED = {
  d: "M0 0",
  fill: "none",
  stroke: "none",
};

/**
 * Seeded by attribute, not by where the attribute sits.
 *
 * This used to look for `r="" data-bind-r=` as one string, which only worked
 * because the cards happened to emit the plain attribute immediately before
 * its binding. The Lite set sorts every element's attributes alphabetically,
 * so `data-bind-r` now comes first and the pair never met — and 112 cards
 * shipped with `r=""`, which the browser rejects as an invalid length.
 *
 * An empty value is invalid for every attribute a card drives, so any empty
 * one belongs to a binding and can be seeded on sight.
 */
function seedAttrs(markup, attrs) {
  let out = markup;
  for (const attr of attrs) {
    // A length wants a number; a path wants a moveto; a paint wants a paint.
    const seed = ATTR_SEED[attr] ?? "0";
    out = out.split(` ${attr}=""`).join(` ${attr}="${seed}"`);
  }
  return out;
}

function extract(path, label, toolId) {
  const html = readFileSync(path, "utf8");
  const lines = html.split(/\r?\n/);

  // ---- the stage, and everything inside it -------------------------
  const stageLine = lines.findIndex((line) => line.includes('class="bimac-stage"'));
  if (stageLine < 0) throw new Error(`${label}: no .bimac-stage`);
  const sectionEnd = lines.findIndex((line) => line.trim() === "</section>");
  if (sectionEnd < 0) throw new Error(`${label}: no closing </section>`);

  const styleMatch = lines[stageLine].match(/style="([^"]*)"/);
  if (!styleMatch) throw new Error(`${label}: stage has no style`);

  // The stage is rebuilt rather than patched.
  //
  // The cards do not agree on how they frame themselves: most are a padded
  // flex row holding the text column beside the drawing, but some are an
  // unpadded column with the padding on a wrapper inside. Keeping each card's
  // own stage was fine while the whole of it shipped; now that only the text
  // column does, a card of the second kind loses the padding with the wrapper
  // and sits flush against its own border.
  //
  // So every card gets the same frame, and only its colours are carried over.
  const original = styleMatch[1];
  const carry = (property, fallback) =>
    // Anchored, so `color` is not read out of `background-color`.
    (original.match(new RegExp(`(?:^|;)\\s*${property}:\\s*([^;]+)`)) ?? [, fallback])[1].trim();

  const style = [
    `width: ${STAGE_WIDTH}px`,
    `height: ${STAGE_HEIGHT}px`,
    "box-sizing: border-box",
    "padding: 30px 48px 36px 48px",
    "display: flex",
    `background-color: ${carry("background-color", "#FFFFFF")}`,
    `color: ${carry("color", "#16181C")}`,
    "overflow: hidden",
  ].join("; ");

  // The line before </section> closes the stage, so the stage's own children
  // run from the line after it to the line before that.
  // Which attributes this card drives. The design lists them itself, and the
  // list differs per card — most drive none, a few drive d, r, cx or fill.
  const attrsMatch = html.match(/var ATTRS = (\[[^\]]*\])/);
  const attrs = attrsMatch ? JSON.parse(attrsMatch[1]) : [];

  const raw = lines.slice(stageLine + 1, sectionEnd - 1).join("\n");
  const markup = seedAttrs(
    dropPanel(fitHeading(swapLockup(renameProduct(raw, toolId, label), label), label), label),
    attrs,
  );
  if (!markup.trim()) throw new Error(`${label}: empty stage`);

  // ---- the value function, verbatim --------------------------------
  const from = html.indexOf("renderVals() {");
  if (from < 0) throw new Error(`${label}: no renderVals`);
  const to = html.indexOf("\n}\n", from);
  if (to < 0) throw new Error(`${label}: renderVals does not close`);
  let body = html.slice(from + "renderVals() {".length, to);

  // Its only tie to the class it came from is where it reads the clock.
  const readsClock = "var p = (this.state && typeof this.state.p === 'number') ? this.state.p : 88;";
  if (!body.includes(readsClock)) throw new Error(`${label}: unexpected renderVals preamble`);
  body = body.replace(readsClock, "// p is the argument.");

  // ---- the loop length ---------------------------------------------
  const loop = html.match(/% (1[0-9]000)\)/);
  if (!loop) throw new Error(`${label}: cannot find the loop length`);

  // Which attributes this card drives. The design lists them itself, and the
  const title = (html.match(/<title>([^<]*)<\/title>/) ?? [, label])[1];

  return {
    style,
    markup,
    body,
    loopMs: Number(loop[1]),
    attrs,
    title,
    // The design's own box was 1280x616 around a drawing that is no longer
    // there. What ships is the column and the padding that framed it.
    width: STAGE_WIDTH,
    height: STAGE_HEIGHT,
  };
}

function emit(moduleName, toolId, card) {
  const source = `/* eslint-disable */
// @ts-nocheck
/**
 * ${card.title}
 *
 * Generated by scripts/build-cards.mjs — do not edit. Both halves come out of
 * the design verbatim: \`markup\` is its stage, and \`values\` is its own
 * renderVals, untouched apart from taking the clock as an argument instead of
 * reading it off a component. See the script for the few things it adjusts.
 */

export const id = ${JSON.stringify(toolId)};
export const title = ${JSON.stringify(card.title)};
export const width = ${card.width};
export const height = ${card.height};
export const loopMs = ${card.loopMs};

/**
 * The attributes this card drives, as the design lists them.
 *
 * Each bound node carries data-bind-<attr> holding a template like "[[wx]]",
 * which the scene fills from the frame's values.
 */
export const attrs = ${JSON.stringify(card.attrs)};

/** The stage's own styles, off the design's root element. */
export const stage = ${styleToObject(card.style)};

export const markup = ${BT}
${escapeForTemplate(card.markup)}
${BT};

/** Everything the markup binds to, for one position in the loop. */
export function values(p) {${card.body}}

const card = { id, title, width, height, loopMs, attrs, stage, markup, values };
export default card;
`;
  writeFileSync(join(OUT_DIR, `${moduleName}.ts`), source);
}

