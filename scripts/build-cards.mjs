/**
 * Turn the designed tool cards into modules the site can render.
 *
 * Each card in `cards/<discipline>/` is a finished, self-contained piece of
 * design: a fixed 1280-wide stage, and a script that drives every moving part
 * of it off one number between 0 and 100. Rewriting either half by hand would
 * only be a chance to get one of a few hundred nodes wrong, so neither is
 * rewritten — this pulls the markup and the value function out verbatim and
 * emits them as a module. `CardScene` supplies the clock.
 *
 * Run it whenever a card is added or redrawn:
 *
 *   node scripts/build-cards.mjs
 *
 * The generated files are committed, so a build never depends on this having
 * been run; this is only how they are refreshed.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, basename } from "node:path";

const CARDS_DIR = "cards";
const OUT_DIR = join("src", "components", "marketplace", "cards");

/**
 * Where the cards live, and how a card becomes a tool id.
 *
 * cards/<software>/<discipline>/NN-name.html, and the id is derived from that
 * path — the same derivation scripts/build-catalogue.mjs uses, so the cards
 * and the catalogue cannot disagree about what a tool is called. A card with
 * no matching tool is still emitted; the site simply never asks for it.
 */
const SOFTWARE = ["revit", "autocad"];
const DISCIPLINES = ["architecture", "structure", "mep"];
const SHORT = { architecture: "arch", structure: "str", mep: "mep" };

function toolIdFor(software, discipline, file) {
  const slug = basename(file, ".html").replace(/^\d+-/, "");
  return `${software === "revit" ? "revit" : "acad"}-${SHORT[discipline]}-${slug}`;
}

