/**
 * The lockup, per application.
 *
 * A card ends in a bar saying what it plugs into, drawn as an orange rule with
 * "Add-in for / Autodesk® Revit®" beside it — or AutoCAD, on the AutoCAD
 * cards. The house cards use the vendor's own lockup instead: the product tile
 * with the name next to it. Those should not be two different things on the
 * same page, so the designed cards are swapped over here rather than by hand
 * in a hundred and twelve files that get redrawn.
 *
 * Matched on the block's own contents rather than on where it sits.
 */
const PRODUCTS = {
  Revit: { logo: "/logos/revit.png", label: "Revit" },
  AutoCAD: { logo: "/logos/autocad.png", label: "AutoCAD" },
};

/**
 * The drawn lockup, matched rather than quoted.
 *
 * It used to be compared as an exact string, which broke the day the cards
 * were redrawn: the Lite set is identical except that the orange rule is 32px
 * tall instead of 34px, and every one of the 112 cards silently kept the
 * design's own lockup instead of the site's. A pattern that lets the rule be
 * any height survives that, and says out loud which part is allowed to vary.
 */
const DRAWN_LOCKUP =
  /<div style="display: flex; align-items: center; gap: 14px;"><div style="width: 3px; height: \d+px; border-radius: 2px; background: #F28C28;"><\/div><div style="display: flex; flex-direction: column; gap: 2px;"><div style="font-size: 12px; color: #5A626E;">Add-in for<\/div><div style="font-family: Archivo, 'Arial Narrow', sans-serif; font-stretch: 88%; font-weight: 700; font-size: 18px; color: #172B4D;">Autodesk® (Revit|AutoCAD)®<\/div><\/div><\/div>/g;

/**
 * The lockup the site puts in its place: "Add-in for", a rule, the product's
 * own mark.
 *
 * The mark carries the product name better than setting it as type beside the
 * mark did — that repeated "Revit" twice, once as a logo and once as a word.
 * The name stays in the image's alt text, which is where a screen reader
 * wants it anyway.
 */
const houseLockup = (product) =>
  '<div style="display: flex; align-items: center; gap: 14px;">' +
  '<div style="font-size: 15px; font-weight: 600; letter-spacing: -0.1px; color: #16181C; white-space: nowrap;">Add-in for</div>' +
  '<div style="width: 1px; height: 30px; background: #D5D9DF;"></div>' +
  `<img src="${PRODUCTS[product].logo}" alt="Autodesk ${PRODUCTS[product].label}" width="34" height="34" style="display: block; width: 34px; height: 34px; object-fit: contain;">` +
  "</div>";

function swapLockup(markup, label) {
  let swapped = 0;
  const out = markup.replace(DRAWN_LOCKUP, (_, product) => {
    swapped += 1;
    return houseLockup(product);
  });
  if (!swapped) console.warn(`  ${label}: no add-in lockup to swap — left as drawn`);
  return out;
}

/* ------------------------------------------------------------------ */
/* The panel                                                           */
/* ------------------------------------------------------------------ */

/**
 * The card without its drawing.
 *
 * Every card is one flex row of two children: a 380px column carrying the
 * name, the line under it and the add-in row, and beside it the panel the
 * animation plays in. The panel comes out, so what is published is what the
 * tool is called and what it does — no mock of the application, no diagram of
 * how it works.
 *
 * Dropping it lets the card shrink from 1280 wide to the column plus the
 * stage's own padding, which is the whole point: the type is then rendered at
 * nearly full size instead of the third of it a 1280-wide card was scaled to.
 *
 * Every column is held at one height, so the add-in rows — pinned to
 * the bottom of their column — line up across a row of cards.
 */
const COLUMN = /<div style="width: 380px; flex-shrink: 0; height: (\d+)px;/;

/** The column, its padding, and the box they need. */
const COLUMN_WIDTH = 380;
const COLUMN_HEIGHT = 290;
const STAGE_WIDTH = COLUMN_WIDTH + 48 + 48;
const STAGE_HEIGHT = COLUMN_HEIGHT + 30 + 36;

function dropPanel(markup, label) {
  const at = markup.search(COLUMN);
  if (at < 0) {
    console.warn(`  ${label}: no text column found — left whole`);
    return markup;
  }

  // Walk to the tag that closes the column; everything after it is the panel.
  let depth = 0;
  let i = at;
  let end = -1;
  while (i < markup.length) {
    const open = markup.indexOf("<div", i);
    const close = markup.indexOf("</div>", i);
    if (close < 0) break;
    if (open >= 0 && open < close) {
      depth += 1;
      i = open + 4;
    } else {
      depth -= 1;
      i = close + 6;
      if (depth === 0) {
        end = i;
        break;
      }
    }
  }
  if (end < 0) {
    console.warn(`  ${label}: text column does not close — left whole`);
    return markup;
  }

  return markup
    .slice(at, end)
    .replace(COLUMN, `<div style="width: ${COLUMN_WIDTH}px; flex-shrink: 0; height: ${COLUMN_HEIGHT}px;`);
}

/* ------------------------------------------------------------------ */
/* The heading                                                         */
/* ------------------------------------------------------------------ */

/**
 * Every heading gets the same height, and nothing else is touched.
 *
 * This used to resize the type itself, on the assumption that the cards all
 * set their titles at 50px and the long ones needed stepping down. They do
 * not: the design sizes each one for its own name, from 50px for "Schedule"
 * down to 27px for "MEP Coordination & Clash Detection", and every one of
 * them is already fitted to two lines in the column. Re-deriving that from a
 * character count only undid it — short names were being *enlarged* to 50px,
 * which is why the cards no longer agreed with each other.
 *
 * So the size is the design's. All this does is hold the block at two lines
 * of the largest of them, so that the line under the heading and the add-in
 * row below it sit at the same height on every card in a row.
 */

/**
 * One title size for every card, matching the rest of the site.
 *
 * The designs set each title for its own name — 49px for "Schedule", 26px for
 * "MEP Coordination & Clash Detection" — which is right when a card is looked
 * at on its own and wrong the moment a hundred of them sit in a grid. Worse,
 * the stage scales to the card's width at very nearly 1:1, so a 49px title
 * arrived on screen at roughly twice the 24px the back of the same card sets
 * its heading at. Turning the card over changed the size of its own name.
 *
 * 26px is the floor of the measured set, which is what makes it the one size
 * that is safe to use flat: every name is already known to fit two lines at
 * it, so nothing overruns the column. Scaled into the card it lands at ~24px
 * — the `card-title-lg` step in tailwind.config.ts, which is where the rest
 * of the site's cards now get their headings from. Change both together.
 */
const CARD_TITLE_PX = 26;

/** Two lines at the size above, at the 1.0 leading the designs set. */
const HEADING_BLOCK = 56;

/**
 * The size each heading fits two lines at, measured in the browser.
 *
 * The design sizes every title for its own name, and for most of them that is
 * already two lines in a 380px column. A couple of dozen are not: once the
 * drawing came out and the card shrank to the column, names like "MEP
 * Coordination & Clash Detection" ran to three lines and four.
 *
 * These sizes come from measuring the rendered text in the real face — text
 * width scales linearly with size, so the largest size that fits is one
 * division away. Estimating it from a character count is what broke this
 * before: no per-character average survives condensed Archivo.
 *
 * Regenerate with scratchpad/sizes.cjs against a running build.
 */
const HEADING_SIZES = JSON.parse(readFileSync(join("scripts", "heading-sizes.json"), "utf8"));

/** The heading as the measurement saw it: tags gone, entities decoded. */
const headingKey = (inner) =>
  inner
    .replace(/<[^>]+>/g, "")
    .replace(/&amp;/g, "&")
    .replace(/&nbsp;/g, " ")
    .replace(/\s+/g, " ")
    .trim();

/**
 * Hold every heading to two lines, and every block to the same height.
 *
 * The size is the design's own unless it overruns the column, and the floor
 * under the block is what keeps the line below the heading — and the add-in
 * row under that — level across a row of cards.
 */
function fitHeading(markup, label) {
  const HEAD = /<h1 style="([^"]*)">([\s\S]*?)<\/h1>/;
  const found = markup.match(HEAD);
  if (!found) {
    console.warn(`  ${label}: no heading to align — left as drawn`);
    return markup;
  }

  const [whole, style, inner] = found;
  const declared = Number((style.match(/font-size:\s*([\d.]+)px/) ?? [, 0])[1]);
  const measured = HEADING_SIZES[headingKey(inner)];
  // The house size, unless this particular name was measured as needing to be
  // smaller still to hold two lines. In practice the measured floor *is* the
  // house size, so this is a guard rather than a source of variation.
  const fits = measured && declared ? Math.min(declared, measured) : declared;
  const size = Math.min(fits || CARD_TITLE_PX, CARD_TITLE_PX);

  const fitted = (size ? style.replace(/font-size:\s*[\d.]+px/, `font-size: ${size}px`) : style)
    .concat(` min-height: ${HEADING_BLOCK}px;`);

  return markup.replace(whole, `<h1 style="${fitted}">${inner}</h1>`);
}

