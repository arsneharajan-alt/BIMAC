/* Adjustments made on the way out                                     */
/* ------------------------------------------------------------------ */

const BT = String.fromCharCode(96);
const BS = String.fromCharCode(92);

/**
 * Make a block of markup safe to sit inside a template literal.
 *
 * Backslashes first, or the escapes added after would be escaped in turn. The
 * cards are hand-built HTML and do contain backslashes — a Windows export path
 * in the exporter card, for one — so this is not theoretical.
 */
function escapeForTemplate(markup) {
  return markup
    .split(BS)
    .join(BS + BS)
    .split(BT)
    .join(BS + BT)
    .split("$" + "{")
    .join(BS + "$" + "{");
}

/**
 * Names the cards were drawn with, against the names they are sold under.
 *
 * A card is a finished design and its copy is not rewritten here — with one
 * exception: the name on the card has to be the name in the catalogue, or a
 * visitor reads one thing on the artwork and another on the back of the same
 * card. Site & Massing was drawn while it was still called Site & Feasibility;
 * the rest of that card, subhead included, is already about massing.
 *
 * Keyed by tool id so it survives the files being renumbered or redrawn, and
 * applied across the whole card: the add-in names its own ribbon panel inside
 * the mocked Revit session, and a card whose title says one thing while its
 * ribbon says another reads as a mistake.
 */
const PRODUCT_RENAMES = {};

function renameProduct(markup, toolId, label) {
  const rename = PRODUCT_RENAMES[toolId];
  if (!rename) return markup;
  const [from, to] = rename;
  if (!markup.includes(from)) {
    console.warn(`  ${label}: nothing says "${from}" any more — rename skipped`);
    return markup;
  }
  return markup.split(from).join(to);
}

